ALTER TABLE relay_messages
    ADD COLUMN relay_sequence BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN delivery_lease_instance UUID REFERENCES relay_instances(instance_id),
    ADD COLUMN delivery_lease_expires_at TIMESTAMPTZ,
    ADD COLUMN delivery_attempts INTEGER NOT NULL DEFAULT 0
        CHECK (delivery_attempts >= 0);

CREATE UNIQUE INDEX relay_messages_sequence_idx
    ON relay_messages(relay_sequence);

CREATE INDEX relay_messages_conversation_sequence_idx
    ON relay_messages(sender_user_id, sender_device_id,
                      recipient_user_id, recipient_device_id,
                      relay_sequence DESC);
